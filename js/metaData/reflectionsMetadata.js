export function getLesson(lessonId) {
  const lesson = lessons[lessonId];

  if (!lesson) {
    console.warn(`Unknown lesson ID: ${lessonId}`);
    return {
      id: lessonId,
      title: "Untitled Lesson",
    };
  }

  return lesson;
}

export function getReflectionMetadata(reflectionId) {
  const reflection = reflections[reflectionId];

  if (!reflection) {
    console.warn(`Unknown reflection ID: ${reflectionId}`);
    return {
      reflectionId,
      lessonId: null,
      reflectionTitle: "Reflection",
      competencies: [],
      designPrinciples: [],
      learningOutcomes: [],
      whatYouPracticed: "Reflection practice information is not available.",
      howThisBuildsYourSkills: "Skill-building information is not available.",
    };
  }

  return reflection;
}
